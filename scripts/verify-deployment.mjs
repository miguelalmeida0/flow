import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { assertDeployable, hashArtifact } from './release-policy.mjs';
const m=JSON.parse(process.env.FLOW_GATE_MANIFEST || '{}');
const sha=process.env.FLOW_RELEASE_SHA;
assert(/^[a-f0-9]{40}$/.test(sha || ''),'Exact 40-character candidate SHA required');
assert(['refs/heads/main','refs/heads/test','refs/heads/release/safe-production'].includes(process.env.GITHUB_REF),'Unsupported deployment branch');
assert.equal(execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),sha);
assertDeployable(m,sha,hashArtifact('dist'));
const run=JSON.parse(readFileSync('candidate-run.json','utf8'));
assert.equal(run.head_sha,sha);assert.equal(run.conclusion,'success');assert.equal(run.event,'push');
assert.equal(run.path,'.github/workflows/release-ci.yml');
assert(['main','test','release/safe-production'].includes(run.head_branch));
assert.equal(run.repository.full_name,process.env.GITHUB_REPOSITORY);
const ci=JSON.parse(readFileSync('candidate-evidence/release-manifest.json','utf8'));
assert.equal(ci.gitSha,sha);assert.equal(ci.artifactHash,m.artifactHash);assert.equal(ci.dirty,false);
assert.equal(ci.dependencyLockHash,m.dependencyLockHash);
assert.equal(m.dependencyLockHash,createHash('sha256').update(readFileSync('package-lock.json')).digest('hex'));
for(const key of ['install','lint','unit','server','releasePolicy','python','build','design','e2e','dependencyAudit'])assert.equal(ci.results[key]?.status,'PASS',key);
writeFileSync('deployment-manifest.json',JSON.stringify({...m,candidateRunId:run.id,previousMain:process.env.FLOW_PREVIOUS_MAIN,previousPages:process.env.FLOW_PREVIOUS_PAGES},null,2));
console.log(`Authorized exact artifact ${m.artifactHash} from ${sha}`);
